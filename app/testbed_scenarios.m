function S = testbed_scenarios()
%TESTBED_SCENARIOS  Reference trajectories for the OMR test bench.
%
%   Each scenario replaces the body of the "MATLAB Function" block that
%   generates [qr, dqr, ddqr, d] in model_OMR_extend_R2022b.slx, so the very
%   same controller/plant is exercised with a different reference.
%
%   Every reference starts on the robot's initial pose q0 = [0.4 -0.4 0.3] so
%   that the initial transient stays inside the barrier; the shipped model
%   diverges if it is started far away from the reference.

S = struct('name', {}, 'T', {}, 'code', {}, 'note', {});

% 1) the paper's figure-eight ------------------------------------------------
S(1).name = 'fig8';
S(1).T = 80;
S(1).note = '22482 case study: 1.5 sin(0.1t), sin(0.2t), sin(0.1t)';
S(1).code = sprintf([ ...
'function [qr,dqr,ddqr,d] = refer_disturbance(t)\n', ...
'qr1 = 1.5*sin(0.1*t);\n', ...
'qr2 = sin(0.2*t);\n', ...
'qr3 = sin(0.1*t);\n', ...
'qr = [qr1;qr2;qr3];\n', ...
'dqr1 = 0.15*cos(0.1*t);\n', ...
'dqr2 = 0.2*cos(0.2*t);\n', ...
'dqr3 = 0.1*cos(0.1*t);\n', ...
'dqr = [dqr1;dqr2;dqr3];\n', ...
'ddqr1 = -0.015*sin(0.1*t);\n', ...
'ddqr2 = -0.04*sin(0.2*t);\n', ...
'ddqr3 = -0.01*sin(0.1*t);\n', ...
'ddqr = [ddqr1;ddqr2;ddqr3];\n', ...
'd = [0.01*sin(t); 0.01*sin(2*t); 0.01*sin(3*t)];\n']);

% 2) circle, starting on q0 -------------------------------------------------
S(2).name = 'circle';
S(2).T = 60;
S(2).note = 'circle of radius 1.0 m, 0.15 rad/s, phase aligned with q0';
S(2).code = sprintf([ ...
'function [qr,dqr,ddqr,d] = refer_disturbance(t)\n', ...
'qr1 = 0.4 + 1.0*sin(0.15*t);\n', ...
'qr2 = -0.4 + 1.0*(1 - cos(0.15*t));\n', ...
'qr3 = 0.3;\n', ...
'qr = [qr1;qr2;qr3];\n', ...
'dqr1 = 0.15*cos(0.15*t);\n', ...
'dqr2 = 0.15*sin(0.15*t);\n', ...
'dqr3 = 0;\n', ...
'dqr = [dqr1;dqr2;dqr3];\n', ...
'ddqr1 = -0.0225*sin(0.15*t);\n', ...
'ddqr2 = 0.0225*cos(0.15*t);\n', ...
'ddqr3 = 0;\n', ...
'ddqr = [ddqr1;ddqr2;ddqr3];\n', ...
'd = [0.01*sin(t); 0.01*sin(2*t); 0.01*sin(3*t)];\n']);

% 3) fast circle: pushes the PNC / saturation layer -------------------------
S(3).name = 'fast_circle';
S(3).T = 40;
S(3).note = 'radius 0.8 m at 0.45 rad/s (0.36 m/s) to excite the PNC layer';
S(3).code = sprintf([ ...
'function [qr,dqr,ddqr,d] = refer_disturbance(t)\n', ...
'qr1 = 0.4 + 0.8*sin(0.45*t);\n', ...
'qr2 = -0.4 + 0.8*(1 - cos(0.45*t));\n', ...
'qr3 = 0.3*cos(0.45*t);\n', ...
'qr = [qr1;qr2;qr3];\n', ...
'dqr1 = 0.36*cos(0.45*t);\n', ...
'dqr2 = 0.36*sin(0.45*t);\n', ...
'dqr3 = -0.135*sin(0.45*t);\n', ...
'dqr = [dqr1;dqr2;dqr3];\n', ...
'ddqr1 = -0.162*sin(0.45*t);\n', ...
'ddqr2 = 0.162*cos(0.45*t);\n', ...
'ddqr3 = -0.06075*cos(0.45*t);\n', ...
'ddqr = [ddqr1;ddqr2;ddqr3];\n', ...
'd = [0.01*sin(t); 0.01*sin(2*t); 0.01*sin(3*t)];\n']);
end
